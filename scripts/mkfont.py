#!/usr/bin/env python3
"""
mkfont.py — 16x32 anti-aliased font for BrainixKernel (2x retina).

Каждый глиф: 32 строки × 16 столбцов, 8-bit alpha per pixel.
При выводе через fb_draw_cp_aa занимает 8×16 логических пикселей
(16×32 физических на 2× фреймбуфере).
"""

import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [
    "/System/Library/Fonts/SFNSMono.ttf",
    "/System/Library/Fonts/Menlo.ttc",
    "/System/Library/Fonts/SFNS.ttf",
    "/System/Library/Fonts/Helvetica.ttc",
    "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
]

# Геометрия в ФИЗИЧЕСКИХ пикселях (2× от логических)
CELL_W     = 16
CELL_H     = 32
BASELINE_Y = 24

FONT_SIZE = 24       # в физических пикселях (было 12 логических)
SCALE     = 4        # SSAA-множитель для рендера

CHARS = [chr(i) for i in range(0x20, 0x80)]
CHARS += [chr(i) for i in range(0x0410, 0x0450)]


def load_font():
    for path in FONTS:
        if not os.path.exists(path):
            continue
        try:
            f = ImageFont.truetype(path, FONT_SIZE * SCALE)
            print(f"[font] loaded: {path} @ {FONT_SIZE}px "
                  f"(SSAA x{SCALE})", file=sys.stderr)
            return f
        except Exception as e:
            print(f"[font] skip {path}: {e}", file=sys.stderr)
    print("[font] no system font found, using default", file=sys.stderr)
    return ImageFont.load_default()


def render(font, ch):
    bw = CELL_W * SCALE
    bh = CELL_H * SCALE
    big = Image.new("L", (bw, bh), 0)
    d = ImageDraw.Draw(big)
    try:
        d.text((0, BASELINE_Y * SCALE), ch, font=font, fill=255, anchor="ls")
    except Exception:
        d.text((0, (BASELINE_Y - FONT_SIZE) * SCALE + 2), ch,
               font=font, fill=255)
    return big.resize((CELL_W, CELL_H), Image.BOX)


def pack(img):
    return [[img.getpixel((c, r)) for c in range(CELL_W)]
            for r in range(CELL_H)]


def main():
    args = [a for a in sys.argv[1:] if a != "auto"]
    out  = args[0] if args else "build/font8x16_aa.c"

    font = load_font()

    glyphs = []
    for ch in CHARS:
        cp = ord(ch)
        cmt = f"0x{cp:02X} '{ch}'" if 0x20 <= cp < 0x7F else f"U+{cp:04X}"
        glyph = pack(render(font, ch))
        rows = []
        for row in glyph:
            rows.append("        {" + ", ".join(f"{v:3d}" for v in row) + "}")
        body = ",\n".join(rows)
        glyphs.append(f"    {{ /* {cmt} */\n{body}\n    }}")

    with open(out, "w") as f:
        f.write("// AUTO-GENERATED by scripts/mkfont.py — do not edit.\n")
        f.write("#include <stdint.h>\n")
        f.write("#include \"font8x16_aa.h\"\n\n")
        f.write(f"// {len(CHARS)} glyphs (96 ASCII + {len(CHARS)-96} Cyrillic)\n")
        f.write("// Format: uint8_t[32][16], 8-bit alpha per pixel (2x retina).\n")
        f.write(f"// SSAA x{SCALE}, render size={FONT_SIZE}px physical.\n\n")
        f.write(f"const uint8_t font8x16_aa[{len(CHARS)}][32][16] = {{\n")
        f.write(",\n".join(glyphs))
        f.write("\n};\n\n")
        f.write(f"const int font8x16_aa_count = {len(CHARS)};\n")

    print(f"[font] {len(CHARS)} glyphs -> {out}", file=sys.stderr)


if __name__ == "__main__":
    main()