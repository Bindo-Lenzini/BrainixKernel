#!/usr/bin/env python3
import os
import sys

def generate(src_dir, out_c):
    files = sorted(
        f for f in os.listdir(src_dir)
        if os.path.isfile(os.path.join(src_dir, f))
    )
    blob = bytearray()
    blob += b'BKRD'
    blob += len(files).to_bytes(4, 'little')
    for name in files:
        path = os.path.join(src_dir, name)
        with open(path, 'rb') as g:
            content = g.read()
        nb = name.encode('utf-8')[:31]
        blob += nb + b'\0' * (32 - len(nb))
        blob += len(content).to_bytes(4, 'little')
        blob += content
    with open(out_c, 'w') as f:
        f.write("// AUTO-GENERATED by scripts/mkinitrd.py — do not edit.\n")
        f.write("#include <stdint.h>\n\n")
        f.write("const uint8_t initrd_data[] = {\n")
        for i in range(0, len(blob), 16):
            chunk = blob[i:i+16]
            f.write("    " + ", ".join(str(b) for b in chunk) + ",\n")
        f.write("};\n\n")
        f.write("const unsigned long initrd_size = sizeof(initrd_data);\n")
    print(f"[initrd] packed {len(files)} files, {len(blob)} bytes -> {out_c}")

if __name__ == '__main__':
    if len(sys.argv) != 3:
        print("usage: mkinitrd.py <src_dir> <out.c>")
        sys.exit(1)
    generate(sys.argv[1], sys.argv[2])
